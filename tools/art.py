def triangle(name):
    rows = []
    for y in range(8):
        r = ''
        for x in range(8):
            on = {'TRI_BR': x + y >= 7, 'TRI_TR': x >= y,
                  'TRI_BL': x <= y, 'TRI_TL': x + y <= 7}[name]
            r += '#' if on else '.'
        rows.append(r)
    return rows


def glyph_bytes():
    out = bytearray()
    for name, rows in GLYPHS:
        rows = rows or triangle(name)
        assert len(rows) == 8 and all(len(r) == 8 for r in rows), name
        for r in rows:
            out.append(int(r.replace('#', '1').replace('.', '0'), 2))
    return bytes(out)


def glyph_defines():
    return ['#define G_%s %d' % (name, FIRST_GLYPH + i) for i, (name, _) in enumerate(GLYPHS)]


