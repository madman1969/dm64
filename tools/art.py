def pointer_bytes():
    rows = POINTER.strip('\n').split('\n')
    assert len(rows) == 21 and all(len(r) == 24 for r in rows)
    out = bytearray()
    for r in rows:
        out += int(r.replace('#', '1').replace('.', '0'), 2).to_bytes(3, 'big')
    return bytes(out + b'\0')



