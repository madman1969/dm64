BITS = {'.': 0, 's': 1, 'B': 2, 'w': 3}


def sprite_bytes():
    """All shapes, four 64-byte sprite blocks each: top-left, top-right, bottom-left, bottom-right."""
    out = bytearray()
    for name in SHAPE_ORDER:
        rows = SHAPES[name].strip('\n').split('\n')
        assert len(rows) == 21 and all(len(r) == 24 for r in rows), name
        # Each art row becomes two sprite rows; each art cell one multicolour pixel (2 bits).
        tall = [r for r in rows for _ in (0, 1)]
        for half_y in (0, 1):
            for half_x in (0, 1):
                block = bytearray()
                for y in range(21):
                    row = tall[half_y * 21 + y][half_x * 12:half_x * 12 + 12]
                    bits = 0
                    for ch in row:
                        bits = (bits << 2) | BITS[ch]
                    block += bits.to_bytes(3, 'big')
                block.append(0)
                out += block
    return bytes(out)
